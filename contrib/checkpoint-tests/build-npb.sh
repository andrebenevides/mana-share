#!/usr/bin/env bash
# Build unmodified NPB 3.4.4 MPI BT/CG with GNU Fortran and MPICH.
set -euo pipefail
: "${NPB_ROOT:?Set NPB_ROOT to the extracted NPB3.4-MPI directory}"
: "${MPICH_HOME:?Set MPICH_HOME to the MPI installation used to build MANA}"
class="${1:-D}"
[[ "$class" =~ ^[SWABCDEF]$ ]] || { echo "Usage: $0 [S|W|A|B|C|D|E|F]" >&2; exit 2; }
[[ -f "$NPB_ROOT/config/make.def.template" ]] || { echo "Invalid NPB_ROOT" >&2; exit 2; }
[[ -x "$MPICH_HOME/bin/mpifort" ]] || { echo "Missing MPICH Fortran wrapper" >&2; exit 2; }
if [[ "$NPB_ROOT" =~ [[:space:]] || "$MPICH_HOME" =~ [[:space:]] ]]; then
    echo "Use paths without whitespace for the NPB Makefiles." >&2
    exit 2
fi

# NPB's setparams reads make.def to report compiler settings in its output.
# Write the real settings there, not only as command-line make overrides.
if [[ -f "$NPB_ROOT/config/make.def" && ! -e "$NPB_ROOT/config/make.def.before-mana" ]]; then
    cp "$NPB_ROOT/config/make.def" "$NPB_ROOT/config/make.def.before-mana"
fi
cat > "$NPB_ROOT/config/make.def" <<EOF
# Generated by MANA contrib/checkpoint-tests/build-npb.sh
MPIFC = $MPICH_HOME/bin/mpifort
FLINK = $MPICH_HOME/bin/mpifort
MPICC = $MPICH_HOME/bin/mpicc
CLINK = $MPICH_HOME/bin/mpicc
CC = gcc
FFLAGS = -O2 -g -fallow-argument-mismatch
FLINKFLAGS = -O2 -g
CFLAGS = -O2 -g
CLINKFLAGS = -O2 -g
FMPI_INC =
FMPI_LIB =
CMPI_INC =
CMPI_LIB =
CONVERTFLAG =
RAND = randi8
BINDIR = ../bin
EOF
# NPB caches interface modules and common objects. Clean when switching class
# or compiler; this target preserves already-built bin/*.x executables.
make -C "$NPB_ROOT" clean
mkdir -p "$NPB_ROOT/bin"
for benchmark in bt cg; do
    # Serial make avoids races in NPB's generated parameters/common modules.
    make -C "$NPB_ROOT" -j1 "$benchmark" CLASS="$class" F08=f SUBTYPE= VERSION=
done
printf 'Built: %s/bin/{bt,cg}.%s.x\n' "$NPB_ROOT" "$class"
